def _call_gemini(
    prompt: str, api_key: str, model: str, temperature: float, max_output_tokens: int, timeout_seconds: float
) -> ExplanationOutput:
    """One real Gemini call using the SDK's native structured output
    (`response_schema=ExplanationOutput`). Wrapped in a thread-based
    timeout, same documented rationale as Phase 12's debate timeout
    (Python cannot forcibly kill a running thread; a genuinely hung call
    leaks one background thread until it eventually completes)."""
    import concurrent.futures

    from google import genai
    from google.genai import types

    def _run() -> ExplanationOutput:
        client = genai.Client(api_key=api_key)
        config = types.GenerateContentConfig(
            system_instruction=SYSTEM_INSTRUCTION,
            temperature=temperature,
            max_output_tokens=max_output_tokens,
            response_mime_type="application/json",
            response_schema=ExplanationOutput,
        )
        response = client.models.generate_content(
            model=model, contents=[types.Content(role="user", parts=[types.Part.from_text(text=prompt)])], config=config
        )
        parsed = response.parsed
        if parsed is None:
            raise RuntimeError("Gemini response could not be parsed into the requested structured schema")
        return parsed

    executor = concurrent.futures.ThreadPoolExecutor(max_workers=1)
    future = executor.submit(_run)
    try:
        result = future.result(timeout=timeout_seconds)
    except concurrent.futures.TimeoutError as exc:
        executor.shutdown(wait=False)  # do not block on a still-running thread -- see module docstring
        raise TimeoutError(f"Gemini call exceeded {timeout_seconds}s") from exc
    executor.shutdown(wait=False)
    return result


