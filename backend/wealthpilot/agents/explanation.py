def build_explanation_input(
    risk: RiskExplanationInput | None,
    compliance: ComplianceExplanationInput,
    financial_health: FinancialHealthExplanationInput | None = None,
    goals: list[GoalExplanationInput] | None = None,
    emergency_fund: EmergencyFundExplanationInput | None = None,
    portfolio: PortfolioExplanationInput | None = None,
    market: MarketExplanationInput | None = None,
    debate_summary: DebateSummaryInput | None = None,
    customer_message: str | None = None,
) -> ExplanationInput:
    return ExplanationInput(
        risk=risk, financial_health=financial_health, goals=goals or [], emergency_fund=emergency_fund,
        portfolio=portfolio, market=market, compliance=compliance, debate_summary=debate_summary,
        customer_message=customer_message,
    )


def explanation_node(state, config=None) -> dict:
    """Graph-compatible wrapper matching Phase 10/11/12's `(state, config)
    -> dict` node contract — standalone, not wired into `agents/graph.py`
    (matches Phase 12's own precedent; this phase's own section 31
    explicitly permits staying standalone "until Phase 14")."""
    from wealthpilot.agents.state import AgentState

    if not isinstance(state, AgentState):
        raise TypeError("explanation_node expects a wealthpilot.agents.state.AgentState")

    if state.compliance_result is None:
        result = ExplanationResult(
            status="failed", output=None, compliance_decision="REJECT", validation_passed=False,
            metadata=ExplanationMetadata(model=DEFAULT_GEMINI_MODEL, temperature=DEFAULT_TEMPERATURE, regeneration_attempts=0),
            failure_reason="invalid_explanation_input: state has no compliance_result",
        )
        return {"explanation_result": result.model_dump()}

    compliance = ComplianceExplanationInput(
        decision=state.compliance_result.decision,
        rules_version=state.compliance_result.rules_version,
        triggered_rule_ids=[rr.rule_id for rr in state.compliance_result.rule_results if rr.triggered],
        reasons=[rr.reason or rr.message for rr in state.compliance_result.rule_results if rr.triggered],
    )
    risk = None
    if state.risk_assessment is not None:
        risk = RiskExplanationInput(
            risk_category=state.risk_assessment.risk_category, confidence=state.risk_assessment.confidence,
            model_version=state.risk_assessment.model_version, data_source=state.risk_assessment.data_source,
            unavailable_reason=state.risk_assessment.unavailable_reason,
        )
    financial_health = None
    if state.financial_health is not None:
        fh = state.financial_health
        financial_health = FinancialHealthExplanationInput(
            expense_persona=fh.expense_persona, expense_persona_unavailable_reason=fh.expense_persona_unavailable_reason,
            savings_rate=fh.savings_rate, behaviour_drift_flag=fh.behaviour_drift_flag,
            isolation_forest_anomaly=fh.isolation_forest_anomaly, model_version=fh.model_version,
            data_source=fh.data_source, unavailable_reason=fh.unavailable_reason,
        )
    goals = [
        GoalExplanationInput(
            goal_type=g.goal_type, nominal_target_amount=g.nominal_target_amount,
            inflation_adjusted_target_amount=g.inflation_adjusted_target_amount,
            required_periodic_contribution=g.required_periodic_contribution, contribution_gap=g.contribution_gap,
            monte_carlo_success_probability=g.monte_carlo_success_probability, feasibility=g.feasibility,
            unavailable_reason=g.unavailable_reason,
        )
        for g in (state.goal_results or [])
    ]
    emergency_fund = None
    if state.emergency_fund is not None:
        ef = state.emergency_fund
        emergency_fund = EmergencyFundExplanationInput(
            required_amount=ef.required_amount, current_amount=ef.current_amount, shortfall=ef.shortfall,
            sufficient=ef.sufficient, unavailable_reason=ef.unavailable_reason,
        )
    portfolio = None
    if state.portfolio_result is not None:
        p = state.portfolio_result
        portfolio = PortfolioExplanationInput(
            strategy=p.strategy, weights=p.weights, expected_return=p.expected_return,
            expected_volatility=p.expected_volatility, sharpe_ratio=p.sharpe_ratio, model_version=p.config_version,
            data_source=p.data_source, unavailable_reason=p.unavailable_reason,
        )
    market = None
    if state.market_analysis is not None:
        market = MarketExplanationInput(
            regime_by_instrument={i.ticker: i.latest_regime for i in state.market_analysis.instruments if i.latest_regime},
            model_version=state.market_analysis.model_version, data_source=state.market_analysis.data_source,
        )

    explanation_input = build_explanation_input(
        risk=risk, compliance=compliance, financial_health=financial_health, goals=goals,
        emergency_fund=emergency_fund, portfolio=portfolio, market=market,
    )

    from wealthpilot.config import get_settings

    settings = get_settings()
    result = run_explanation(explanation_input, api_key=settings.gemini_api_key, model=settings.gemini_model or DEFAULT_GEMINI_MODEL)
    return {"explanation_result": result.model_dump()}
