# Orchestration
# ---------------------------------------------------------------------------


def run_explanation(
    explanation_input: ExplanationInput,
    api_key: str | None = None,
    model: str = DEFAULT_GEMINI_MODEL,
    temperature: float = DEFAULT_TEMPERATURE,
    max_output_tokens: int = DEFAULT_MAX_OUTPUT_TOKENS,
    timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS,
    call_fn=_call_gemini,
) -> ExplanationResult:
    """Runs the explanation generation, or skips it entirely if the
    deterministic compliance decision is REJECT (BUILD_PLAN.md section 11:
    "A REJECT compliance verdict never reaches this node at all" — checked
    FIRST, before any Gemini call). On validation failure, regenerates
    ONCE with a stricter reminder, then falls back to a templated,
    non-LLM explanation rather than ever returning an invalid result
    (BUILD_PLAN.md's own "reject / regenerate / fallback" flow).

    `call_fn` (signature matching `_call_gemini`) is injectable so tests
    can substitute a fake, deterministic response generator instead of a
    real network call — the same dependency-injection pattern Phase 12's
    `model_client_cls` parameter uses, for the same reason (fast,
    deterministic, zero-cost tests; a small number of separate live tests
    exercise the real `_call_gemini` directly).
    """
    decision = explanation_input.compliance.decision

    if decision == "REJECT":
        return ExplanationResult(
            status="skipped_rejected",
            output=None,
            compliance_decision=decision,
            validation_passed=False,
            validation_notes=["compliance_reject_veto: explanation not generated for a REJECTed proposal"],
            metadata=ExplanationMetadata(model=model, temperature=temperature, regeneration_attempts=0),
        )

    if not api_key:
        return ExplanationResult(
            status="failed",
            output=None,
            compliance_decision=decision,
            validation_passed=False,
            metadata=ExplanationMetadata(model=model, temperature=temperature, regeneration_attempts=0),
            failure_reason="configuration_failure: no Gemini API key supplied",
        )

    prompt = _build_user_prompt(explanation_input)
    last_notes: list[str] = []

    for attempt in range(MAX_REGENERATION_ATTEMPTS + 1):
        attempt_prompt = prompt
        if attempt > 0:
            attempt_prompt += (
                "\n\nYour previous response failed validation for the following reason(s): "
                + "; ".join(last_notes)
                + ". Regenerate, using ONLY the numbers already given above, exactly as given."
            )
        try:
            output = call_fn(attempt_prompt, api_key, model, temperature, max_output_tokens, timeout_seconds)
        except TimeoutError as exc:
            return ExplanationResult(
                status="failed", output=None, compliance_decision=decision, validation_passed=False,
                metadata=ExplanationMetadata(model=model, temperature=temperature, regeneration_attempts=attempt),
                failure_reason=f"timeout: {exc}",
            )
        except Exception as exc:  # noqa: BLE001 - any Gemini/network/parsing failure must become a structured failure or trigger the fallback, never crash or fabricate success
            last_notes = [f"api_or_parsing_failure: {type(exc).__name__}: {exc}"]
            continue

        output.disclaimer = CANONICAL_DISCLAIMER  # never trust the model's own disclaimer text
        violations = _validate_output(output, explanation_input)
        if not violations:
            return ExplanationResult(
                status="completed", output=output, compliance_decision=decision, validation_passed=True,
                metadata=ExplanationMetadata(model=model, temperature=temperature, regeneration_attempts=attempt),
            )
        last_notes = violations

    fallback = _templated_fallback_explanation(explanation_input)
    return ExplanationResult(
        status="completed",
        output=fallback,
        compliance_decision=decision,
        validation_passed=False,
        validation_notes=last_notes + ["fell back to a templated, non-LLM explanation after validation failures"],
        metadata=ExplanationMetadata(model=model, temperature=temperature, regeneration_attempts=MAX_REGENERATION_ATTEMPTS),
    )


