"""Phase 13 — Gemini explanation / advisory-language layer.

Gemini's ONLY responsibility: explain already-computed, deterministic
Phase 4-12 results in clear, user-facing prose. It is not a calculator, a
portfolio optimizer, a risk classifier, a compliance engine, a
recommendation-scoring engine, or a market-forecasting engine
(BUILD_PLAN.md section 11: "Gemini CANNOT: calculate financial values,
change a portfolio allocation, override compliance, invent market data,
guarantee returns, execute trades, or transfer money").

**Provider/model**: `google-genai`, reusing the SAME already-configured
credentials and model Phase 12 uses (`settings.gemini_api_key`,
`settings.gemini_model`) — no second API-key configuration, no new
provider. Structured output uses the SDK's native `response_schema`
(confirmed supported directly against the installed `google-genai==0.3.0`
before writing this module) with a Pydantic model as the schema, rather
than free-text parsing — the more robust mechanism BUILD_PLAN.md section
11 itself points to ("Gemini structured-output call").

**Standalone, not wired into `agents/graph.py`** — matching Phase 12's
own precedent exactly (this phase's own section 31 explicitly permits
staying standalone "until Phase 14"). `explanation_node` matches the same
`(state, config) -> dict` contract Phase 10/11/12 use.

**Validation flow** (BUILD_PLAN.md section 11's own diagram, implemented
literally):

    Fully computed dict (risk, health, goals, portfolio, market, compliance)
          |
    Gemini structured-output call
          |
    Response validated: every numeric claim checked against the source
          |
       match -> explanation returned
       mismatch/invented number/guaranteed-return claim/compliance
       violation -> FAIL -> regenerate ONCE -> still failing -> fall back
       to a templated (non-LLM) explanation -- never an invalid result
       reaches the caller.

**Compliance veto, exactly like Phase 12**: "A REJECT compliance verdict
never reaches this node at all" (BUILD_PLAN.md section 11). Checked first,
before any Gemini call. `run_explanation` returns `status="skipped_rejected"`
immediately — the deterministic REJECT (and every earlier analysis result)
is preserved unchanged; nothing here weakens Phase 11's compliance gate.

**The output schema has no numeric field at all** (section 13's own
preferred design: "design the output schema so that Gemini does not need
to return financial numeric fields at all... prose referring to supplied
values... validation ensures prose does not contradict source"). Every
`ExplanationOutput` field is a plain string. Numeric validation therefore
scans the generated PROSE for percentage-like/decimal-like numbers and
checks each against the deterministic source's own values (§ below,
`_validate_numeric_claims`) — a deliberately narrow, disclosed heuristic
(not full NLP semantic parsing), documented as a known limitation in the
Phase 13 report rather than oversold as perfect.

**`disclaimer` is never Gemini-generated.** It is always overwritten,
after parsing, with the EXACT text from PROJECT_PLAN.md's "Disclaimer to
Carry Through the System" section — never trusted from the model's own
output, regardless of what (if anything) it returns for that field.

**A real, twice-confirmed finding from live testing**: this project's
configured Gemini model consumes a large, invisible token budget for
internal processing not reflected in `candidates_token_count` (no
`thinking_config` exists in this pinned SDK version to control it) — a
500-token budget truncated even a 2-field JSON response mid-string in a
live test. `DEFAULT_MAX_OUTPUT_TOKENS` is set generously (8192, larger
than Phase 12's 1024, since this module's output has 9 prose fields
instead of one paragraph) rather than precisely tuned.
"""

