PERCENT_TOLERANCE = 0.6  # percentage points
PLAIN_DECIMAL_TOLERANCE = 0.006
CURRENCY_TOLERANCE = 1.0  # absolute currency units (rounding-safe)

_PERCENT_RE = re.compile(r"(\d+(?:\.\d+)?)\s?%")
# 1-2 digits before the decimal point -- covers Sharpe-like ratios both
# inside [0,1] (e.g. "0.83") AND above 1 (e.g. "2.5"): an earlier version
# of this pattern only matched numbers starting with "0." and so was
# completely blind to an out-of-range claim like a fabricated Sharpe ratio
# of "2.5" -- found and fixed via a failing test, not assumed correct.
_PLAIN_DECIMAL_RE = re.compile(r"(?<![%\d.,\-])\d{1,2}\.\d+(?!\d*%)")
_CURRENCY_RE = re.compile(r"(?<![.\d])(\d{3,}(?:,\d{3})*(?:\.\d+)?)(?!\d*%)")


def _authoritative_percentages(explanation_input: ExplanationInput) -> set[float]:
    """Every 0-1 fraction in the source, normalized to percentage points
    (0-100 scale) -- weights, return, volatility, Monte Carlo probability,
    risk confidence."""
    values: set[float] = set()
    if explanation_input.risk and explanation_input.risk.confidence is not None:
        values.add(round(explanation_input.risk.confidence * 100, 2))
    if explanation_input.portfolio:
        p = explanation_input.portfolio
        if p.weights:
            values.update(round(w * 100, 2) for w in p.weights.values())
        if p.expected_return is not None:
            values.add(round(p.expected_return * 100, 2))
        if p.expected_volatility is not None:
            values.add(round(p.expected_volatility * 100, 2))
    for g in explanation_input.goals:
        if g.monte_carlo_success_probability is not None:
            values.add(round(g.monte_carlo_success_probability * 100, 2))
    return values


def _authoritative_plain_decimals(explanation_input: ExplanationInput) -> set[float]:
    """Values conventionally written as a bare decimal, not a percentage
    (Sharpe ratio) -- kept separate from percentages since "0.83" as a
    Sharpe ratio must not be reinterpreted as "83%"."""
    values: set[float] = set()
    if explanation_input.portfolio and explanation_input.portfolio.sharpe_ratio is not None:
        values.add(round(explanation_input.portfolio.sharpe_ratio, 4))
    return values


def _authoritative_currency_amounts(explanation_input: ExplanationInput) -> set[float]:
    values: set[float] = set()
    for g in explanation_input.goals:
        for v in (g.nominal_target_amount, g.inflation_adjusted_target_amount, g.required_periodic_contribution, g.contribution_gap):
            if v is not None:
                values.add(round(v, 2))
    if explanation_input.emergency_fund:
        e = explanation_input.emergency_fund
        for v in (e.required_amount, e.current_amount, e.shortfall):
            if v is not None:
                values.add(round(v, 2))
    return values


def _validate_numeric_claims(output: ExplanationOutput, explanation_input: ExplanationInput) -> list[str]:
    """Scans every prose field for percentage-like/decimal-like/currency-
    like numbers and checks each against the deterministic source's own
    values. A deliberately narrow heuristic (regex-based, not full NLP
    semantic parsing) -- documented as such in the Phase 13 report, not
    oversold as perfect. Returns a list of violation descriptions (empty
    if everything checks out)."""
    authoritative_pct = _authoritative_percentages(explanation_input)
    authoritative_plain = _authoritative_plain_decimals(explanation_input)
    authoritative_currency = _authoritative_currency_amounts(explanation_input)

    violations: list[str] = []
    for field_name in ExplanationOutput.model_fields:
        if field_name == "disclaimer":
            continue  # always overwritten, never validated
        text = getattr(output, field_name)

        for match in _PERCENT_RE.finditer(text):
            value = float(match.group(1))
            if authoritative_pct and not any(abs(value - a) <= PERCENT_TOLERANCE for a in authoritative_pct):
                violations.append(f"{field_name}: claimed percentage {value}% matches no authoritative value {sorted(authoritative_pct)}")

        for match in _PLAIN_DECIMAL_RE.finditer(text):
            value = float(match.group(0))
            matches_plain = any(abs(value - a) <= PLAIN_DECIMAL_TOLERANCE for a in authoritative_plain)
            # The 0-1 -> percentage reinterpretation only makes sense for a
            # value actually in that range (e.g. "0.83" could plausibly mean
            # "83%") -- a value like "2.5" is never a percentage fraction.
            matches_pct_scaled = (
                0.0 <= value <= 1.0
                and bool(authoritative_pct)
                and any(abs(value * 100 - a) <= PERCENT_TOLERANCE for a in authoritative_pct)
            )
            if authoritative_plain or authoritative_pct:
                if not matches_plain and not matches_pct_scaled:
                    violations.append(f"{field_name}: claimed decimal {value} matches no authoritative value")

        for match in _CURRENCY_RE.finditer(text):
            value = float(match.group(1).replace(",", ""))
            if authoritative_currency and not any(abs(value - a) <= CURRENCY_TOLERANCE for a in authoritative_currency):
                violations.append(f"{field_name}: claimed amount {value} matches no authoritative value")

    return violations


_GUARANTEE_PATTERNS = [
    re.compile(r"\bguarantee(d|s)?\b", re.IGNORECASE),
    re.compile(r"\bwill (achieve|succeed|reach)\b", re.IGNORECASE),
    re.compile(r"\byou are (guaranteed|certain) to\b", re.IGNORECASE),
    re.compile(r"\brisk[- ]free\b", re.IGNORECASE),
]


def _validate_no_guarantees(output: ExplanationOutput) -> list[str]:
    """Section 16/41: a probability must never become a certainty claim."""
    violations = []
    for field_name in ExplanationOutput.model_fields:
        text = getattr(output, field_name)
        for pattern in _GUARANTEE_PATTERNS:
            if pattern.search(text):
                violations.append(f"{field_name}: contains a guarantee-like claim ({pattern.pattern})")
    return violations


def _validate_compliance_consistency(output: ExplanationOutput, explanation_input: ExplanationInput) -> list[str]:
    """Section 14: the prose must not contradict the deterministic
    compliance/emergency-fund state (e.g. claiming compliant when REJECT,
    or sufficient when the emergency fund is insufficient)."""
    violations = []
    decision = explanation_input.compliance.decision
    compliance_text = output.compliance_explanation.lower()
    if decision == "REJECT" and re.search(r"\bis compliant\b|\bcan proceed\b|\bapproved\b", compliance_text):
        violations.append("compliance_explanation contradicts a REJECT decision")
    if decision != "REJECT" and re.search(r"\breject(ed)?\b", compliance_text) and "not reject" not in compliance_text:
        # A PASS/WARN explanation claiming "rejected" is also a contradiction.
        violations.append("compliance_explanation claims rejection despite a non-REJECT decision")

    if explanation_input.emergency_fund and explanation_input.emergency_fund.sufficient is False:
        health_text = (output.financial_health_explanation + " " + output.summary).lower()
        if re.search(r"emergency fund is sufficient|adequate emergency fund", health_text):
            violations.append("explanation claims emergency fund is sufficient despite a deterministic insufficient status")

    return violations


def _validate_output(output: ExplanationOutput, explanation_input: ExplanationInput) -> list[str]:
    return (
        _validate_numeric_claims(output, explanation_input)
        + _validate_no_guarantees(output)
        + _validate_compliance_consistency(output, explanation_input)
    )


