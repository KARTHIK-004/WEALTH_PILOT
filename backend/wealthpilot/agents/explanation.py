def _templated_fallback_explanation(explanation_input: ExplanationInput) -> ExplanationOutput:
    """A safe, deterministic, non-LLM explanation built by plain Python
    string formatting of the source values themselves -- used only when
    Gemini fails validation twice (initial + one regeneration) or the API
    call itself fails. Never contains a number that isn't a direct restate
    of a source value (it IS the source value, formatted)."""

    def _fmt_pct(x: float | None) -> str:
        return "unavailable" if x is None else f"{x * 100:.1f}%"

    risk_text = "Risk classification is unavailable."
    if explanation_input.risk and explanation_input.risk.risk_category:
        risk_text = (
            f"The classified risk category is {explanation_input.risk.risk_category} "
            f"(confidence {_fmt_pct(explanation_input.risk.confidence)})."
        )
    elif explanation_input.risk and explanation_input.risk.unavailable_reason:
        risk_text = f"Risk classification is unavailable: {explanation_input.risk.unavailable_reason}"

    health_text = "Financial-health information is unavailable."
    if explanation_input.financial_health:
        fh = explanation_input.financial_health
        parts = []
        if fh.expense_persona_unavailable_reason:
            parts.append(f"Expense persona is unavailable: {fh.expense_persona_unavailable_reason}.")
        if fh.behaviour_drift_flag is not None:
            parts.append(f"Behaviour drift flag: {fh.behaviour_drift_flag}.")
        if fh.unavailable_reason:
            parts.append(f"Note: {fh.unavailable_reason}")
        health_text = " ".join(parts) if parts else health_text

    goal_lines = []
    for g in explanation_input.goals:
        if g.unavailable_reason:
            goal_lines.append(f"Goal '{g.goal_type}': unavailable ({g.unavailable_reason}).")
        else:
            goal_lines.append(
                f"Goal '{g.goal_type}': target {g.nominal_target_amount}, "
                f"required contribution {g.required_periodic_contribution}, "
                f"feasibility {g.feasibility}, Monte Carlo probability {_fmt_pct(g.monte_carlo_success_probability)}."
            )
    goal_text = " ".join(goal_lines) if goal_lines else "No goal information is available."

    portfolio_text = "Portfolio information is unavailable."
    if explanation_input.portfolio and explanation_input.portfolio.weights:
        p = explanation_input.portfolio
        weight_str = ", ".join(f"{a} {_fmt_pct(w)}" for a, w in p.weights.items())
        portfolio_text = (
            f"Strategy: {p.strategy}. Weights: {weight_str}. "
            f"Expected return {_fmt_pct(p.expected_return)}, volatility {_fmt_pct(p.expected_volatility)}, "
            f"Sharpe ratio {p.sharpe_ratio}."
        )

    market_text = "Market regime information is unavailable."
    if explanation_input.market and explanation_input.market.regime_by_instrument:
        market_text = "Market regimes: " + ", ".join(
            f"{t}: {r}" for t, r in explanation_input.market.regime_by_instrument.items()
        ) + "."

    c = explanation_input.compliance
    compliance_text = f"Compliance decision: {c.decision} (rules version {c.rules_version})."
    if c.reasons:
        compliance_text += " Reasons: " + "; ".join(c.reasons) + "."

    summary = f"Automated explanation unavailable; the following is a direct restatement of the computed results. {risk_text}"

    return ExplanationOutput(
        summary=summary,
        risk_explanation=risk_text,
        financial_health_explanation=health_text,
        goal_explanation=goal_text,
        portfolio_explanation=portfolio_text,
        market_explanation=market_text,
        compliance_explanation=compliance_text,
        limitations="This is a templated, non-generative fallback explanation; a full AI-generated explanation was not available for this run.",
        disclaimer=CANONICAL_DISCLAIMER,
    )


