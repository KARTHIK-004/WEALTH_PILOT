"""Renders the Phase 2 data-quality findings (wealthpilot.data.quality) as
Markdown and writes them to reports/. Run via:

    python -m wealthpilot.data.report

Read-only against datasets/raw/ — only ever writes to reports/.
"""

from __future__ import annotations

import json
from pathlib import Path

from wealthpilot.data.acquisition import FAR_TRANS_DIR, KAGGLE_DIR
from wealthpilot.data.quality import FileQualityReport, generate_far_trans_report, generate_kaggle_report

_REPO_ROOT = Path(__file__).resolve().parents[3]
REPORT_PATH = _REPO_ROOT / "reports" / "phase2_data_quality_report.md"


def _render_file_report(name: str, report: FileQualityReport) -> str:
    lines = [f"### {name}", "", f"- Path: `{report.path}`", f"- Row count: {report.row_count}"]
    if report.columns:
        lines.append(f"- Columns: {', '.join(report.columns)}")
    if report.null_counts:
        nonzero = {k: v for k, v in report.null_counts.items() if v > 0}
        lines.append(f"- Null/empty counts (nonzero only): {nonzero or 'none'}")
    lines.append(f"- Exact full-row duplicates: {report.duplicate_full_rows}")
    for key, value in report.extra.items():
        lines.append(f"- {key}: {value}")
    if report.notes:
        lines.append("- Notes:")
        for note in report.notes:
            lines.append(f"  - {note}")
    lines.append("")
    return "\n".join(lines)


def render_markdown() -> str:
    far_trans = generate_far_trans_report()
    kaggle = generate_kaggle_report()

    parts = [
        "# Phase 2 — Data Quality Report",
        "",
        "Generated by `wealthpilot.data.report`. Read-only against "
        "`datasets/raw/` — regenerate any time with "
        "`python -m wealthpilot.data.report`; this file is committed so the "
        "findings don't have to be retyped by hand.",
        "",
        f"## FAR-Trans (`{FAR_TRANS_DIR}`)",
        "",
    ]
    for name, report in far_trans.items():
        parts.append(_render_file_report(name, report))

    parts.append(f"## Kaggle (`{KAGGLE_DIR}`)")
    parts.append("")
    for name, report in kaggle.items():
        parts.append(_render_file_report(name, report))

    return "\n".join(parts)


def write_report() -> Path:
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(render_markdown(), encoding="utf-8")
    return REPORT_PATH


if __name__ == "__main__":
    path = write_report()
    print(f"wrote {path}")
