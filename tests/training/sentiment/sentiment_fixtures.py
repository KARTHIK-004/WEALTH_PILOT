"""Fixtures for the sentiment training / evaluation tests (ADR-052). The labelled data here is a DEVELOPMENT FIXTURE of invented sentences, generated in the test: it is never training or
validation data for the application, it measures nothing about real accuracy, and a manifest that says so is the only kind these tests feed the code (apart from the synthetic "approved"
manifest used to test the validated path, whose data is equally invented and whose approval is a test double). The fake trainer replaces the deep-learning fine-tuning so the whole
pipeline (split, calibration, metrics, artifact, loader round trip) runs without any deep-learning package or network."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from training.sentiment.config import LABEL_MAP, LABELS
from training.sentiment.train_sentiment_transformer import TrainerOutput

FAKE_REVISION = "0123456789abcdef0123456789abcdef01234567"      # SYNTHETIC: a well-formed commit hash that names nothing; no real revision or Hub id appears in any test
FAKE_IDENTIFIER = "test-double/base-model"
FAKE_VERSIONS = {"torch": "0.0-test-double", "transformers": "0.0-test-double", "tokenizers": "0.0-test-double", "safetensors": "0.0-test-double", "fake_trainer": "test double"}
SUBJECTS = ("savings", "loan", "retirement plan", "emergency fund", "mortgage", "investments", "credit card", "budget", "pension", "salary")
TEXTS = {
    "positive": "I feel {adj} about my {s} number {i}.",
    "negative": "I am {adj} about my {s} number {i}.",
    "neutral": "My {s} number {i} is {adj}.",
}
ADJECTIVES = {"positive": ("confident", "hopeful", "optimistic"), "negative": ("worried", "anxious", "stressed"), "neutral": ("reviewed monthly", "held at one bank", "listed in my budget")}


def make_rows(per_class: int, *, group_every: int = 0) -> list[dict]:
    rows = []
    for label in LABELS:
        for i in range(per_class):
            row = {"text": TEXTS[label].format(adj=ADJECTIVES[label][i % 3], s=SUBJECTS[i % len(SUBJECTS)], i=i), "label": label}
            if group_every:
                row["group"] = f"{label}-author-{i // group_every}"
            rows.append(row)
    return rows


def write_jsonl(path: Path, rows: list, extra_lines: list[str] | None = None) -> Path:
    lines = [json.dumps(r) for r in rows] + (extra_lines or [])
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def manifest_dict(**over) -> dict:
    base = {
        "dataset_id": "dev-fixture", "version": "1", "source": "invented sentences generated by the test suite", "url": "none (generated)", "license": "none: invented test text",
        "language": "en", "label_definitions": {l: f"the sentence expresses {l} sentiment" for l in LABELS}, "label_map": {l: l for l in LABELS}, "sample_count": 90,
        "preprocessing": "validate_text; case-insensitive duplicate removal", "split_policy": {"train": 0.8, "validation": 0.1, "test": 0.1, "seed": 42}, "duplicate_policy": "exact duplicates once; conflicts removed",
        "limitations": ["invented; measures nothing real"], "domain_note": "a development fixture, not validation data", "approved": False, "approved_by": "", "development_fixture": True,
        "has_intensity": False, "intensity_definition": "",
    }
    base.update(over)
    return base


def approved_manifest(**over) -> dict:
    """A TEST DOUBLE of an approved dataset (invented sentences): exists only to exercise the validated path of the pipeline."""
    return manifest_dict(**{**dict(dataset_id="approved-double", license="test-double licence", approved=True, approved_by="test double", development_fixture=False), **over})


def write_manifest(path: Path, raw: dict) -> Path:
    path.write_text(json.dumps(raw), encoding="utf-8")
    return path


def fake_trainer(*, accuracy_noise: float = 1.0, seed: int = 7):
    """Writes stand-in weight / config / tokenizer files and returns logits derived from the true labels plus seeded noise. Nothing here is a real model."""

    def train(train_rows, validation_rows, test_rows, directory: Path) -> TrainerOutput:
        rng = np.random.default_rng(seed)
        (directory / "model.safetensors").write_bytes(b"stand-in weights (test double)")
        (directory / "config.json").write_text(json.dumps({"id2label": {str(i): l for i, l in enumerate(LABELS)}, "vocab_size": 5000, "max_position_embeddings": 514}), encoding="utf-8")
        (directory / "tokenizer_config.json").write_text(json.dumps({"model_max_length": 512}), encoding="utf-8")
        (directory / "vocab.txt").write_text("a\nb\n", encoding="utf-8")

        def logits(rows):
            out = rng.normal(0.0, accuracy_noise, size=(len(rows), len(LABELS)))
            for i, row in enumerate(rows):
                out[i, LABEL_MAP[row.label]] += 3.0
            return out

        return TrainerOutput(logits(validation_rows), logits(test_rows), 5000, 4990, ["tokenizer_config.json", "vocab.txt"], dict(FAKE_VERSIONS),                      # tokenizer shorter than the (padded) matrix
                             base_model_revision=FAKE_REVISION, tokenizer_identifier=FAKE_IDENTIFIER, tokenizer_revision=FAKE_REVISION)

    return train
